"""Generate skin.kscape's colour themes (skin.kscape/colors/*.xml).

Usage: python3 tools/gen_colors.py

KScape is drawn in two colours: a main colour (the blue of the info screen, the list band, the
tabs and bars, and the bluish text on dark backgrounds) and a highlight colour (the amber of the
selection frame, sort letters and badges). Every view, the skin's and the add-on's, uses the
named colours below, so a theme only has to give them new values.

defaults.xml is Blue with Amber. Every other main / highlight pair gets a file named
"<Main> - <Highlight>", the name Kodi's skin colours setting (lookandfeel.skincolors) takes;
Skin settings sets it (script.kscape.wall's colours.py). Each shade of the main colour keeps its
lightness and transparency and takes the theme's hue, with its saturation scaled as the theme's
base colour is to the default blue's, so contrast stays as designed.
"""
import colorsys
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'skin.kscape', 'colors')

# Shades of the main colour, as designed in Blue (ARGB).
MAIN = {
    'kscape_bg': 'FF070B16',             # backgrounds (a very dark tint)
    'kscape_bg_chip': 'EB070B16',        # the now-playing chip
    'kscape_bg_shade': 'E6070B16',       # Home: darkening under the bar and caption
    'kscape_bg_veil': '99070B16',        # Home: light shade under the clock
    'kscape_glow': '30245BD3',           # the soft glow behind settings panels
    'kscape_blue': 'FF1F5BD3',           # panels, the list band, focused rows
    'kscape_blue_dark': 'FF184CB9',      # button strips, progress tracks on blue
    'kscape_blue_head': 'FF3876E4',      # headers, the parent tab while its submenu has focus
    'kscape_blue_focus': 'FF5A9DF2',     # the focused tab, button or column
    'kscape_blue_light': 'FF4E8DF2',     # the focused row on the info and album screens
    'kscape_blue_mid': 'FF2A66D8',       # the album and show screens' selected tab
    'kscape_blue_bar': 'EE1F5BD3',       # the bottom bars
    'kscape_blue_quiet': '701F5BD3',     # the collections band while the tab bar has focus
    'kscape_strip': 'D8101C3A',          # the Home submenu strip
    'kscape_track': 'FF16264A',          # progress tracks on dark backgrounds
    'kscape_track_dark': 'FF13284F',
    'kscape_text': 'FFF0F4FF',           # text on dark backgrounds
    'kscape_text_dim': 'FFA9C2F2',
    'kscape_text_off': 'FF7F93BF',
    'kscape_text_faint': '80F0F4FF',
    'kscape_tint_row': 'FFE6EAF2',       # list rows
    'kscape_tint_cast': 'FFA9C6FF',      # the list's cast column
    'kscape_tint_director': 'FFCCD9F2',
    'kscape_tint_light': 'FFD6E2FF',     # secondary text on blue panels
    'kscape_tint_sub': 'FFDCE6FA',
    'kscape_tint_soft': 'FF9AB4E6',      # Now Playing: secondary text
}
FIXED = {'white': 'FFFFFFFF', 'kscape_dim': 'C0000000'}
BASE = MAIN['kscape_blue']

# Theme name: base colour (RGB). Graphite is a near-grey.
MAINS = {
    'Blue': '1F5BD3',
    'Crimson': 'C0283C',
    'Emerald': '17935A',
    'Violet': '6A3FC8',
    'Teal': '13879A',
    'Graphite': '4A5160',
}
HIGHLIGHTS = {
    'Amber': 'F5A01A',
    'White': 'F2F2F2',
    'Cyan': '35D0E8',
    'Lime': 'A6E22E',
    'Rose': 'FF5C8A',
}
DEFAULT = ('Blue', 'Amber')


def hls(rgb):
    r, g, b = (int(rgb[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return colorsys.rgb_to_hls(r, g, b)


def retint(argb, base_rgb):
    """`argb` (a shade of the default blue) moved to the hue and saturation of `base_rgb`."""
    a, rgb = argb[:2], argb[2:]
    h, l, s = hls(rgb)
    bh, _, bs = hls(BASE[2:])
    th, _, ts = hls(base_rgb)
    s2 = min(1.0, s * (ts / bs if bs else 0))
    r, g, b = colorsys.hls_to_rgb((th + (h - bh)) % 1.0, l, s2)
    return a + ''.join(f'{round(c * 255):02X}' for c in (r, g, b))


def palette(main, highlight):
    colors = dict(FIXED)
    colors.update({k: retint(v, MAINS[main]) if main != 'Blue' else v for k, v in MAIN.items()})
    colors['kscape_amber'] = 'FF' + HIGHLIGHTS[highlight]
    return colors


def file_name(main, highlight):
    return 'defaults.xml' if (main, highlight) == DEFAULT else f'{main} - {highlight}.xml'


def write(main, highlight):
    colors = palette(main, highlight)
    body = ''.join(f'\t<color name="{k}">{v}</color>\n' for k, v in colors.items())
    xml = (f'<?xml version="1.0" encoding="UTF-8"?>\n'
           f'<!-- GENERATED by tools/gen_colors.py: KScape in {main} with {highlight} highlights. -->\n'
           f'<colors>\n{body}</colors>\n')
    with open(os.path.join(OUT, file_name(main, highlight)), 'w') as f:
        f.write(xml)


def main():
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        if old.endswith('.xml'):
            os.remove(os.path.join(OUT, old))
    for m in MAINS:
        for h in HIGHLIGHTS:
            write(m, h)
    print(f'wrote {len(MAINS) * len(HIGHLIGHTS)} colour files to {OUT}')


if __name__ == '__main__':
    main()
