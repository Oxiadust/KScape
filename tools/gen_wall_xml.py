"""Generate script.kscape.wall's window XML from its geometry module.

Usage: python3 tools/gen_wall_xml.py
Control ids (k = 0..POOL-1):
  900          focus sink (keeps Kodi delivering actions to the window)
  1000         camera group: positioned at -camera, glides via runtime slide animations
  1001         amber focus frame (inside camera group, under the covers)
  1100+k       pool A cover slot group; 1300+k fallback title textbox; 1500+k poster
  2100+k       pool B cover slot group; 2300+k fallback title textbox; 2500+k poster
  1900         info panel group; 1901 title; 1902 synopsis
  1950         status label (loading / empty library), outside the camera group

No <visible> tags on Python-driven controls: a visibility condition overrides setVisible().
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), '..', 'script.kscape.wall')
sys.path.insert(0, ROOT)
from resources.lib import geometry as G  # noqa: E402

POOL = G.POOL_COLS * G.POOL_ROWS
CARD = 'FF1A1A1F'
AMBER = 'FFF5A01A'
PANEL_BLUE = 'FF1F5BD3'


def slot(base):
    out = []
    for k in range(POOL):
        out.append(f'''			<control type="group" id="{base + k}">
				<width>{G.COVER_W}</width>
				<height>{G.COVER_H}</height>
				<control type="image">
					<width>{G.COVER_W}</width>
					<height>{G.COVER_H}</height>
					<texture colordiffuse="{CARD}">kscape-white.png</texture>
				</control>
				<control type="textbox" id="{base + 200 + k}">
					<left>12</left>
					<top>12</top>
					<width>{G.COVER_W - 24}</width>
					<height>{G.COVER_H - 24}</height>
					<align>center</align>
					<aligny>center</aligny>
					<font>kscape_small</font>
					<textcolor>FFC8C8D0</textcolor>
				</control>
				<control type="image" id="{base + 400 + k}">
					<width>{G.COVER_W}</width>
					<height>{G.COVER_H}</height>
					<aspectratio>scale</aspectratio>
					<fadetime>120</fadetime>
				</control>
			</control>''')
    return '\n'.join(out)


def main():
    panel_w = G.PANEL_CELLS * G.PITCH_X - (G.PITCH_X - G.COVER_W)
    xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/gen_wall_xml.py from resources/lib/geometry.py. Do not edit by hand. -->
<window>
	<defaultcontrol always="true">900</defaultcontrol>
	<controls>
		<control type="image">
			<width>{G.SCREEN_W}</width>
			<height>{G.SCREEN_H}</height>
			<texture colordiffuse="FF060607">kscape-white.png</texture>
		</control>
		<control type="button" id="900">
			<description>Focus sink: the window handles all navigation itself</description>
			<left>-200</left>
			<top>-200</top>
			<width>1</width>
			<height>1</height>
			<texturefocus/>
			<texturenofocus/>
		</control>
		<control type="group" id="1000">
			<description>Camera</description>
			<control type="image" id="1001">
				<description>Focus frame</description>
				<width>{G.COVER_W + 2 * G.FRAME}</width>
				<height>{G.COVER_H + 2 * G.FRAME}</height>
				<texture colordiffuse="{AMBER}">kscape-white.png</texture>
			</control>
{slot(1100)}
{slot(2100)}
			<control type="group" id="1900">
				<description>Info panel beside the focused cover</description>
				<width>{panel_w}</width>
				<height>{G.COVER_H}</height>
				<animation effect="fade" start="0" end="100" time="220">Visible</animation>
				<animation effect="fade" start="100" end="0" time="120">Hidden</animation>
				<control type="image">
					<width>{panel_w}</width>
					<height>{G.COVER_H}</height>
					<texture colordiffuse="{PANEL_BLUE}">kscape-white.png</texture>
				</control>
				<control type="label" id="1901">
					<left>34</left>
					<top>26</top>
					<width>{panel_w - 68}</width>
					<height>56</height>
					<font>kscape_panel_title</font>
					<textcolor>FFFFFFFF</textcolor>
				</control>
				<control type="textbox" id="1902">
					<left>34</left>
					<top>88</top>
					<width>{panel_w - 68}</width>
					<height>{G.COVER_H - 112}</height>
					<font>kscape_panel_body</font>
					<textcolor>FFF0F4FF</textcolor>
				</control>
			</control>
		</control>
		<control type="label" id="1950">
			<left>360</left>
			<top>500</top>
			<width>1200</width>
			<height>80</height>
			<align>center</align>
			<aligny>center</aligny>
			<font>kscape_title</font>
			<textcolor>FFE6E6EA</textcolor>
		</control>
	</controls>
</window>
'''
    out = os.path.join(ROOT, 'resources', 'skins', 'Default', '1080i', 'script-kscape-wall.xml')
    with open(out, 'w') as f:
        f.write(xml)
    print(f'wrote {out} ({POOL} slots per pool)')


if __name__ == '__main__':
    main()
